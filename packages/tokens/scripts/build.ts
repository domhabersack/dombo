// Generates every distributable from src/tokens.ts. Run with `node` (type stripping).
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import colors from 'tailwindcss/colors'
import tokens, { fonts, motion, palette, shades } from '../src/tokens.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'dist')
mkdirSync(dist, { recursive: true })

type Scale = Record<string, string>
const tw = colors as unknown as Record<string, Scale>

// Tailwind v4 ships oklch(); email and image tools need hex.
function oklchToHex(value: string): string {
  const m = value.match(/oklch\(\s*([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)/)
  if (!m) return value
  const L = Number(m[1]) / (m[2] ? 100 : 1)
  const C = Number(m[3])
  const h = (Number(m[4]) * Math.PI) / 180
  const a = C * Math.cos(h)
  const b = C * Math.sin(h)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const mm = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  const rgb = [
    4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s,
  ]
  return (
    '#' +
    rgb
      .map((x) => (x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055))
      .map((x) => Math.round(Math.min(1, Math.max(0, x)) * 255).toString(16).padStart(2, '0'))
      .join('')
  )
}

const roles = Object.entries(palette) as [keyof typeof palette, string][]
const fontStack = (list: string[]) => list.join(', ')

// --- theme.css (Tailwind v4) ------------------------------------------------
const keyframes = `
  @keyframes fade-in { from { opacity: 0 } }
  @keyframes fade-up { from { opacity: 0; transform: translateY(var(--motion-distance-md)) } }
  @keyframes scale-in { from { opacity: 0; transform: scale(0.96) } }
  @keyframes slide-in-right { from { opacity: 0; transform: translateX(var(--motion-distance-lg)) } }
  @keyframes shimmer { to { background-position: -200% 0 } }`

const themeCss = `/* Generated by @domhabersack/tokens. Do not edit; change src/tokens.ts. */

/*
 * dark: applies under <html data-theme="dark">, or when the OS prefers dark
 * and data-theme="light" isn't set. Without the attribute it follows the OS,
 * so no JavaScript is needed unless you offer a switch.
 */
@custom-variant dark {
  &:where([data-theme='dark'], [data-theme='dark'] *) {
    @slot;
  }
  @media (prefers-color-scheme: dark) {
    &:where(:not([data-theme='light'], [data-theme='light'] *)) {
      @slot;
    }
  }
}

@theme {
${roles
  .map(([role, name]) =>
    shades.map((shade) => `  --color-${role}-${shade}: ${tw[name][shade]};`).join('\n'),
  )
  .join('\n')}

  --font-sans: ${fontStack(fonts.sans)};
  --font-display: ${fontStack(fonts.display)};
  --font-mono: ${fontStack(fonts.mono)};

${Object.entries(motion.ease)
  .map(([k, v]) => `  --ease-${k}: ${v};`)
  .join('\n')}

  --animate-fade-in: fade-in ${motion.duration.slow}ms ${motion.ease.out} both;
  --animate-fade-up: fade-up ${motion.duration.slower}ms ${motion.ease.out} both;
  --animate-scale-in: scale-in ${motion.duration.base}ms ${motion.ease.out} both;
  --animate-slide-in-right: slide-in-right ${motion.duration.slow}ms ${motion.ease.out} both;
  --animate-shimmer: shimmer 1.6s linear infinite;
${keyframes}
}
`

// --- motion.css (framework-agnostic) ----------------------------------------
const motionCss = `/* Generated by @domhabersack/tokens. Works with or without Tailwind. */
:root {
${Object.entries(motion.duration)
  .map(([k, v]) => `  --motion-duration-${k}: ${v}ms;`)
  .join('\n')}
${Object.entries(motion.ease)
  .map(([k, v]) => `  --motion-ease-${k}: ${v};`)
  .join('\n')}
${Object.entries(motion.distance)
  .map(([k, v]) => `  --motion-distance-${k}: ${v};`)
  .join('\n')}
}
${keyframes.replace(/^ {2}/gm, '')}

/*
 * Scroll reveal. Elements are only hidden once a script has opted in with
 * <html data-reveal>, so the page is complete without JavaScript.
 * The script adds .is-visible when the element enters the viewport.
 */
:root[data-reveal] [data-animate] {
  opacity: 0;
  transition:
    opacity var(--motion-duration-slower) var(--motion-ease-out),
    transform var(--motion-duration-slower) var(--motion-ease-out);
}
:root[data-reveal] [data-animate='fade-up'] { transform: translateY(var(--motion-distance-lg)); }
:root[data-reveal] [data-animate='scale-in'] { transform: scale(0.97); }
:root[data-reveal] [data-animate].is-visible { opacity: 1; transform: none; }

/*
 * Motion is optional. It is off when the OS asks for reduced motion (unless
 * the visitor explicitly opts in with data-motion="on"), or when
 * data-motion="off" is set.
 */
@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion='on']) *,
  :root:not([data-motion='on']) *::before,
  :root:not([data-motion='on']) *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
  :root:not([data-motion='on']) [data-animate] { opacity: 1 !important; transform: none !important; }
}
:root[data-motion='off'] *,
:root[data-motion='off'] *::before,
:root[data-motion='off'] *::after {
  animation-duration: 0.01ms !important;
  animation-iteration-count: 1 !important;
  transition-duration: 0.01ms !important;
  scroll-behavior: auto !important;
}
:root[data-motion='off'] [data-animate] { opacity: 1 !important; transform: none !important; }
`

// --- tokens.json (resolved values) ------------------------------------------
const resolvedColors = Object.fromEntries(
  roles.map(([role, name]) => [
    role,
    {
      tailwind: name,
      ...Object.fromEntries(
        shades.map((shade) => [shade, { oklch: tw[name][shade], hex: oklchToHex(tw[name][shade]) }]),
      ),
    },
  ]),
)
const json = {
  ...tokens,
  colors: resolvedColors,
  white: '#ffffff',
  black: '#000000',
}

// --- UnoCSS preset (for Slidev) ---------------------------------------------
const unoColors = Object.fromEntries(
  roles.map(([role, name]) => [
    role,
    Object.fromEntries(shades.map((shade) => [shade, oklchToHex(tw[name][shade])])),
  ]),
)
const unoJs = `// Generated by @domhabersack/tokens.
/** UnoCSS preset that adds the design system's colors, fonts and motion to preset-wind. */
export function presetDombo() {
  return {
    name: '@domhabersack/preset',
    theme: ${JSON.stringify(
      {
        colors: unoColors,
        fontFamily: {
          sans: fontStack(fonts.sans),
          display: fontStack(fonts.display),
          mono: fontStack(fonts.mono),
        },
        easing: Object.fromEntries(Object.entries(motion.ease)),
      },
      null,
      2,
    ).replace(/\n/g, '\n    ')},
  }
}
export default presetDombo
`

const indexJs = `// Generated by @domhabersack/tokens.
export const tokens = ${JSON.stringify(json, null, 2)}
export default tokens
`

const files: Record<string, string> = {
  'theme.css': themeCss,
  'motion.css': motionCss,
  'tokens.json': JSON.stringify(json, null, 2) + '\n',
  'uno.js': unoJs,
  'index.js': indexJs,
}
for (const [name, content] of Object.entries(files)) writeFileSync(join(dist, name), content)
console.log(`tokens: wrote ${Object.keys(files).join(', ')}`)
